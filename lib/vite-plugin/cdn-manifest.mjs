import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { CDN_ASSET, PINNED_VENDOR_FILES, PROBE_URL, siteUrl } from '../config.mjs';
import { publicPath } from './catalog.mjs';

function isCdnCandidate(vendorPath) {
  return vendorPath.endsWith('/react@18.3.1.js')
    || vendorPath.endsWith('/react-dom@18.3.1.js')
    || CDN_ASSET.test(vendorPath);
}

export function compileCdnManifest(snapshot, basePath) {
  const manifest = {};
  for (const file of snapshot.files) {
    if (!file.sourceUrl || PINNED_VENDOR_FILES.has(file.path) || !isCdnCandidate(file.path)) continue;
    manifest[siteUrl(basePath, publicPath(file.path))] = file.sourceUrl;
  }
  if (!Object.values(manifest).includes(PROBE_URL)) {
    throw new Error('CDN fallback manifest is missing the favicon probe.');
  }
  return manifest;
}

export async function writeCdnManifest(snapshot, basePath, file) {
  await mkdir(path.dirname(file), { recursive: true });
  const manifest = compileCdnManifest(snapshot, basePath);
  const source = [
    '// Generated by lib/vite-plugin/cdn-manifest.mjs. Do not edit.',
    `export const probeUrl = ${JSON.stringify(PROBE_URL)};`,
    `export default ${JSON.stringify(manifest)};`,
    ''
  ].join('\n');
  await writeFile(file, source);
}
